"""
Biohub - Cell Tracking During Development
Milestone 16: hidden-rerun-robust reference learned-graph one-cell runner.

Milestone 13's audit found the competition's high-scoring reference
solution (a learned UNet + node-transformer + ILP graph-optimization
pipeline) architecturally unrelated to our own classical + gradient-
boosted-classifier stack, and NOT replicable offline at that time because
its support artifact was not mounted. That artifact has since been made
available as a Kaggle dataset (a "support pack" containing the reference
repo, its offline dependency wheels, and its trained edge-predictor
weights), and a manual public run succeeded end to end. This module
packages that manual run into a single, hidden-rerun-robust one-cell
runner: it materializes the reference repo, installs ONLY its bundled
wheels, runs its GPU predict script, converts the emitted GEFF
predictions into a competition submission.csv, and validates the result -
with a top-level graceful fallback so a VALID submission.csv always
exists even if the learned pipeline fails on a hidden rerun.

This is an ORCHESTRATION module, not one of our own tracking pipelines:
the heavy lifting (wheel install, GPU inference, ILP solve) happens on
Kaggle where the artifact is mounted and a GPU is present. It never
retrains anything, never calls the Kaggle submission API, and never
triggers Save Version - it only writes files under /kaggle/working.

Hidden-rerun robustness (the reason this milestone exists):

  - Dynamic split generation: the reference's shipped
    kaggle_test_splits_50ep.json carries PUBLIC test-dataset names, so a
    hidden rerun (which mounts DIFFERENT, unknown dataset names) would
    hand the predict script names that don't exist and crash. This runner
    NEVER uses the static public splits as primary: at runtime it
    discovers the actually-mounted test dataset names (from the test dir
    and/or sample_submission.csv), rewrites the splits file for the
    current data, and VERIFIES every split-0 name exists on disk before
    prediction. The public names (44b6_0113de3b, 44b6_0b24845f,
    6bba_05b6850b, 6bba_05db0fb1) are never hardcoded into any submitted
    output.

  - Hidden-safe validation: the expected dataset set is taken from the
    mounted sample_submission.csv (or the mounted test dir) - never a
    hardcoded public set - so validation checks against whatever data is
    actually present in the rerun.

  - Top-level fallback: any unhandled failure in the learned pipeline is
    caught; if no submission.csv was produced, a valid one is written
    from sample_submission.csv (exact columns, no missing structural
    values) so a hidden failure scores low instead of throwing a
    "Notebook Threw Exception" (which scores nothing). The runner re-
    raises ONLY if even the fallback cannot be written.

  - Environment detection keyed on /kaggle/input (the definitive Kaggle
    marker) - a stray /kaggle/working directory created by a local dry
    run can never flip an off-Kaggle execution into attempting a real
    (impossible) run, which keeps notebook execution clean off-Kaggle.

The manual zarr v3 reader and GEFF layout knowledge are copied from
Milestone 15 (not imported). No prior milestone's files are modified.
"""

