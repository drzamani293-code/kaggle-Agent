def run_milestone16_pipeline(working_dir: str = KAGGLE_WORKING_DIR, competition_dir: str = KAGGLE_COMPETITION_INPUT_DIR) -> dict:
    """Runs the self-tests always. On Kaggle (definitive marker
    /kaggle/input present) runs the full learned-graph pipeline through the
    top-level fallback (which guarantees a valid submission.csv or, if even
    the fallback fails, re-raises). Off Kaggle, stays a clean self-test-only
    dry run - the learned pipeline cannot run without the mounted support-
    pack artifact and a GPU, so it is not attempted, keeping notebook
    execution error-free everywhere.
    """
    print("=== Self-test: dynamic splits, GEFF conversion, validation, fallback ===")
    run_milestone16_tests()

    if not is_kaggle_env():
        print(
            "[dry-run] /kaggle/input absent - self-tests only. The reference learned-graph "
            "pipeline runs only on Kaggle where the support-pack artifact is mounted and a GPU "
            "is available. No submission.csv is written in a dry run."
        )
        return {"status": "dry_run"}

    return run_with_fallback(working_dir, competition_dir)


